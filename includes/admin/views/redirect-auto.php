<?php
if ( ! defined( 'ABSPATH' ) ) { exit; }
require_once ACE_SEO_PATH . 'includes/frontend/class-ace-seo-term-redirect.php';
$taxonomies = get_taxonomies( array( 'public' => true ) );
$terms = $taxonomies ? get_terms( array( 'taxonomy' => array_values( $taxonomies ), 'hide_empty' => false, 'number' => 31,
    'offset' => ( $page - 1 ) * 30, 'orderby' => 'term_id', 'order' => 'ASC',
    'meta_query' => array( array( 'key' => ACE_SEO_Term_Redirect::META_KEY, 'value' => '', 'compare' => '!=' ) ) ) ) : array();
$resolver = new ACE_SEO_Term_Redirect();
?>
<section class="ace-redirect-card ace-redirect-tab-panel">
    <h2>Auto redirects</h2>
    <p><strong>Automatic redirects from retention recommendations are not implemented yet.</strong> There is no retention auto-redirect switch to enable. Recommendations require an administrator to choose a suitable destination and save a redirect.</p>
    <p>Weekly retention checks are <strong><?php echo empty( $options['auto_build'] ) ? 'off' : 'on'; ?></strong>. These refresh the report only. Age-based search expiry, notices and the lighter archive view do not apply 301 redirects.</p>
    <p><a class="button" href="<?php echo esc_url( $settings_url ); ?>">Manage retention settings</a> <a href="<?php echo esc_url( $report_url ); ?>">Review retention report</a></p>
    <h3>Configured archive redirects</h3>
    <p>These separate category, tag and taxonomy rules run when their archives are visited. They are read-only here; use the archive editor to manage them. They are not generated by retention, and do not redirect the articles inside an archive.</p>
    <?php if ( is_wp_error( $terms ) ) : ?>
        <p role="alert">Archive rules could not be loaded. Try again.</p>
    <?php else : ?>
    <div class="ace-redirect-table"><table class="widefat striped"><thead><tr><th>Source archive</th><th>Destination / state</th><th>Manage</th></tr></thead><tbody>
    <?php foreach ( array_slice( $terms, 0, 30 ) as $term ) :
        $target = $resolver->resolve_target( $term );
        $source = get_term_link( $term );
        $taxonomy = get_taxonomy( $term->taxonomy ); ?>
        <tr><td><strong><?php echo esc_html( $term->name ); ?></strong><br><?php echo esc_html( $taxonomy->labels->singular_name ); ?><br><?php if ( ! is_wp_error( $source ) ) { echo esc_html( $source ); } ?></td>
        <td><?php echo esc_html( $target ?: (string) get_term_meta( $term->term_id, ACE_SEO_Term_Redirect::META_KEY, true ) ); ?><br><strong><?php echo $target ? '301 — configured' : 'Not served — target could not be resolved'; ?></strong></td>
        <td><?php if ( current_user_can( 'edit_term', $term->term_id ) ) : ?><a class="button" href="<?php echo esc_url( get_edit_term_link( $term->term_id, $term->taxonomy ) ); ?>">Manage archive</a><?php else : ?>Requires archive editing permission<?php endif; ?></td></tr>
    <?php endforeach; ?>
    <?php if ( ! $terms ) : ?><tr><td colspan="3">No configured archive redirects.</td></tr><?php endif; ?>
    </tbody></table></div>
    <?php AceSeoRedirectDiscovery::pagination( 'auto', $page, count( $terms ) > 30 ); ?>
    <?php endif; ?>
    <p class="description">Post redirects approved through the retention report are listed under Existing redirects. This view lists saved Ace SEO archive rules; redirects supplied only by custom code or the web server are not inventoried here.</p>
</section>
